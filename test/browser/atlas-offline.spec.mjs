import {test,expect} from '@playwright/test';
import {pathToFileURL} from 'node:url';
import {checkOfflineChartScroll} from './helpers.mjs';
test('A125 atlas contact sheet and witness reopen offline with exact selected data',async({page,context},info)=>{
  const fixture=process.env.TAMEROP_ATLAS_HTML;
  expect(fixture,'Generate TAMEROP_ATLAS_HTML with the A125 native owner').toBeTruthy();
  const requests=[],errors=[];
  page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
  page.on('websocket',s=>requests.push(s.url()));page.on('pageerror',e=>errors.push(e.message));
  await context.setOffline(true);await page.goto(pathToFileURL(fixture).href);
  await expect(page.locator('html')).toHaveAttribute('data-ready','true');
  const data=await page.locator('#portable-visual-data').evaluate(el=>JSON.parse(el.textContent));
  expect(data.states.map(s=>s.id)).toEqual(['contact','filling']);
  await page.getByLabel('Saved view',{exact:true}).selectOption('filling');
  await expect(page.locator('html')).toHaveAttribute('data-selected-state','filling');
  const filling=data.states.find(s=>s.id==='filling');
  await expect(page.locator('#saved-selection')).toHaveText(filling.selection);
  expect(filling.plotted_json).toContain('kernel_dimension');
  expect(filling.plotted_json).toContain('coefficients');
  const pending=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download selected values',exact:true}).click();
  const download=await pending;
  const {readFile}=await import('node:fs/promises');
  expect(await readFile(await download.path(),'utf8')).toBe(filling.plotted_json);
  await page.screenshot({path:info.outputPath('atlas-offline-wide.png'),fullPage:true});
  await page.setViewportSize({width:480,height:900});
  await checkOfflineChartScroll(page,page.getByRole('region',{name:'Saved figure',exact:true}),page.locator('#saved-figure'));
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.reload();await expect(page.locator('html')).toHaveAttribute('data-selected-state','filling');
  await page.screenshot({path:info.outputPath('atlas-offline-narrow.png'),fullPage:true});
  expect(requests).toEqual([]);expect(errors).toEqual([]);
});
