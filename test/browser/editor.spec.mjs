import { test, expect } from '@playwright/test';
import { state, keyboardActivate, openInspector, capture } from './helpers.mjs';
import { readFile } from 'node:fs/promises';
const base=`http://127.0.0.1:${process.env.TAMEROP_BROWSER_SLICE_PORT||8849}`;
const inputs=new Set(["order","dimensions","field","source","target","matrix","rows","columns","vertex","upsets","downsets"]);
const control=(p,s)=>p.locator(`${inputs.has(s)?"input":""}[id^="tamerop-module-editor-"][id$="-${s}"]`);
async function input(p,s,t){const c=control(p,s);await c.fill(t);await c.press('Tab');}
async function action(p,s){const old=(await state(p)).summary.revision;await keyboardActivate(control(p,s));
  await expect.poll(async()=>(await state(p)).summary.revision,{timeout:120000}).toBeGreaterThan(old);
  await expect(control(p,'error')).toBeEmpty();
  await expect.poll(async()=>(await state(p)).summary.listener_errors).toEqual([]);}
async function ready(p){await p.waitForFunction(()=>[...document.querySelectorAll('canvas')].some(c=>c.wglmakie_screen?.renderer?.info.render.frame>0),null,{timeout:180000});}
test('A99 edit failed paths, exact matrices, order, fields, history, exports and linked cleanup',async({page},info)=>{
  const errors=[];await openInspector(page,`${base}/editor`,errors);await ready(page);
  await expect(control(page,'status')).toContainText('Valid module');
  await input(page,'source','3');await input(page,'target','4');await action(page,'select');
  await input(page,'matrix','2');await action(page,'apply-matrix');
  const invalid=await state(page);expect(invalid.validation.valid).toBe(false);
  expect(invalid.validation.witness.first.rows).toEqual([['1']]);
  expect(invalid.validation.witness.second.rows).toEqual([['2']]);
  await expect(control(page,'readout')).toContainText('different composites');
  await page.getByText('Export checked code or retain this draft',{exact:true}).click();
  await expect(control(page,'generate')).toBeDisabled();
  await expect(control(page,'code-download')).toBeHidden();
  await capture(page,info,'failed-diamond');
  await action(page,'undo');expect((await state(page)).validation.valid).toBe(true);
  await action(page,'redo');expect((await state(page)).validation.valid).toBe(false);
  await action(page,'undo');
  const before=(await state(page)).summary.revision;
  await input(page,'matrix','run(`no`)');await keyboardActivate(control(page,'apply-matrix'));
  await expect(control(page,'error')).not.toBeEmpty();expect((await state(page)).summary.revision).toBe(before);
  await input(page,'matrix','1/3');await action(page,'apply-matrix');
  expect((await state(page)).validation.witness.second.rows).toEqual([['1//3']]);
  await action(page,'undo');
  await input(page,'field','F3');await action(page,'apply-field');
  expect((await state(page)).validation.valid).toBe(true);
  await page.getByText('Edit the finite order and stalks',{exact:true}).click();
  await input(page,'order','1 1 1 1; 0 1 0 1; 0 0 1 1; 1 0 0 1');await action(page,'apply-order');
  expect((await state(page)).validation.valid).toBe(false);await action(page,'undo');
  await input(page,'dimensions','1 1 1 2');await action(page,'apply-order');
  expect((await state(page)).validation.valid).toBe(false);
  await action(page,'undo');
  await control(page,'generate').click();await expect(control(page,'code')).toContainText('PModule');
  const downloadPromise=page.waitForEvent('download');await control(page,'code-download').click();
  const download=await downloadPromise;expect(await readFile(await download.path(),'utf8')).toContain('C.Fp(3)');
  await control(page,'archive').click();await expect(control(page,'archive-download')).toHaveAttribute('href',/^data:/,{timeout:120000});
  const archivePromise=page.waitForEvent('download');await control(page,'archive-download').click();
  const archive=await archivePromise;const json=JSON.parse(await readFile(await archive.path(),'utf8'));
  expect(json.kind).toBe('TamerOpVisualSession');
  const linked=await page.context().newPage();await openInspector(linked,`${base}/editor`,errors);await ready(linked);
  await input(linked,'source','3');await input(linked,'target','4');await action(linked,'select');
  await input(linked,'matrix','2');await action(linked,'apply-matrix');
  await expect.poll(async()=>(await state(page)).validation.valid).toBe(false);
  await linked.close();await expect.poll(async()=>(await state(page)).viewer_count,{timeout:45000}).toBe(1);
  await page.setViewportSize({width:480,height:900});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  const chart=page.getByLabel('Module editor diagram',{exact:true});
  await chart.focus();await chart.press('ArrowRight');
  await expect.poll(()=>chart.evaluate(element=>element.scrollLeft)).toBeGreaterThan(0);
  await action(page,'undo');await capture(page,info,'narrow-editor');
  await control(page,'close').click();await expect.poll(async()=>(await state(page)).summary.closed).toBe(true);
  await expect.poll(async()=>(await state(page)).viewer_count).toBe(0);expect(errors).toEqual([]);
});
test('A99 presentation support closure and active zero coefficients',async({page},info)=>{
  const errors=[];await openInspector(page,`${base}/editor-presentation`,errors);await ready(page);
  await input(page,'vertex','2');await action(page,'select');
  await expect(control(page,'readout')).toContainText('Dimension: 1');
  await input(page,'matrix','0');await action(page,'apply-matrix');
  await expect(control(page,'readout')).toContainText('Dimension: 0');
  await action(page,'undo');
  await page.getByText('Edit indicator supports',{exact:true}).click();
  await input(page,'upsets','2');await action(page,'apply-supports');
  expect((await state(page)).validation.valid).toBe(false);await capture(page,info,'invalid-upset');
  await action(page,'undo');await expect(control(page,'readout')).toContainText('Dimension: 1');
  await control(page,'close').click();await expect.poll(async()=>(await state(page)).summary.closed).toBe(true);
  expect(errors).toEqual([]);
});
