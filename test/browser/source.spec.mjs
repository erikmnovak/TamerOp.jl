import {test, expect} from '@playwright/test';
import {state, control, openInspector, selected, pick, capture, fullyClosed} from './helpers.mjs';
const base=`http://127.0.0.1:${process.env.TAMEROP_BROWSER_SLICE_PORT||8849}`;
async function representative(page,member=1){
  await control(page,'member').fill(String(member));
  await control(page,'apply-member').click();
  await expect.poll(async()=>(await state(page)).selection.member).toBe(member);
  await control(page,'representative').check();
  await expect.poll(async()=>(await state(page)).representative?.source_geometry,{timeout:120_000}).toBe('verified_source_cells');
  await expect(control(page,'source-overlays').locator('canvas')).toHaveCount(1);
  await page.waitForFunction(()=>[...document.querySelectorAll('[id$="-source-overlays"] canvas')].every(c=>c.wglmakie_screen?.renderer?.info.render.frame>0));
  await expect.poll(async()=>(await state(page)).summary.listener_errors).toEqual([]);
}
test('A43 ring: source cycle, death filling, linked views, reset and closure',async({page,context},info)=>{
  const errors=[];await openInspector(page,`${base}/source`,errors);
  expect((await state(page)).panels.length).toBe(3);
  await pick(page,1,'barcode');
  await representative(page);
  expect((await state(page)).panels.length).toBe(5);
  await expect(control(page,'readout')).toContainText('original boundary equations are verified');
  await control(page,'source-overlays').scrollIntoViewIfNeeded();
  await capture(page,info,'ring-source-cycle-and-filling');
  const linked=await context.newPage();await openInspector(linked,`${base}/source`,errors);
  await expect(control(linked,'source-overlays').locator('canvas')).toHaveCount(1);
  const valid=(await state(page)).selection;
  await control(page,'member').fill('999');await control(page,'apply-member').click();
  await expect(control(page,'error')).not.toBeEmpty();
  expect((await state(page)).selection).toEqual(valid);
  expect((await state(page)).panels.length).toBe(5);
  await control(linked,'reset').click();await selected(page,null);
  await expect(control(page,'source-overlays').locator('canvas')).toHaveCount(0);
  await linked.close();
  await expect.poll(async()=>(await state(page)).viewer_count,{timeout:45_000}).toBe(1);
  await control(page,'interval').focus();await page.keyboard.press('Home');
  await page.keyboard.press('ArrowDown');await page.keyboard.press('Tab');await selected(page,1);
  await representative(page);
  await page.setViewportSize({width:480,height:900});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await capture(page,info,'source-narrow');
  await control(page,'close').click();await fullyClosed(page);
  await expect(control(page,'source-overlays').locator('canvas')).toHaveCount(0);
  expect(errors).toEqual([]);
});
test('A43 torus: duplicate members and periodic seam geometry',async({page},info)=>{
  const errors=[];await openInspector(page,`${base}/source-periodic`,errors);
  await pick(page,1,'diagram');
  await control(page,'representative').click();
  await expect(control(page,'error')).not.toBeEmpty();
  await expect(control(page,'representative')).not.toBeChecked();
  await representative(page,1);
  await expect(control(page,'readout')).toContainText('Periodic seams identify opposite faces');
  const first=(await state(page)).representative.cycle.cell_indices;
  expect((await state(page)).panels.length).toBe(4);
  await capture(page,info,'first-periodic-generator');
  await control(page,'member').fill('2');await control(page,'apply-member').click();
  await expect(control(page,'source-overlays').locator('canvas')).toHaveCount(0);
  await representative(page,2);
  expect((await state(page)).representative.cycle.cell_indices).not.toEqual(first);
  expect((await state(page)).representative.bounding_chain).toBeNull();
  await capture(page,info,'second-periodic-generator');
  await control(page,'close').click();await fullyClosed(page);
  expect(errors).toEqual([]);
});
